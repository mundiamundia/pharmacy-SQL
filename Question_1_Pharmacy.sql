DROP SCHEMA IF EXISTS q1_pharmacy CASCADE;
CREATE SCHEMA q1_pharmacy;
SET search_path TO q1_pharmacy, public;

CREATE TABLE medicines (
  medicine_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medicine_name varchar(100) NOT NULL,
  unit_price numeric(10,2) NOT NULL CHECK (unit_price > 0),
  stock_qty integer NOT NULL CHECK (stock_qty >= 0)
);
CREATE TABLE sales (
  sale_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medicine_id integer NOT NULL REFERENCES medicines(medicine_id),
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_price numeric(10,2) NOT NULL CHECK (unit_price > 0),
  sold_on date NOT NULL
);
CREATE TABLE stock_audit (
  audit_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medicine_id integer NOT NULL REFERENCES medicines(medicine_id),
  old_qty integer NOT NULL,
  new_qty integer NOT NULL,
  changed_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE daily_sales (
  sales_date date PRIMARY KEY,
  total_qty bigint NOT NULL,
  total_amount numeric(14,2) NOT NULL
);

